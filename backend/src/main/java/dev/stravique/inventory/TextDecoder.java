package dev.stravique.inventory;

import org.mozilla.universalchardet.UniversalDetector;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.charset.CharacterCodingException;
import java.nio.charset.Charset;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;

@Component
public class TextDecoder {

    private static final List<String> FALLBACK_CHARSETS = List.of("Shift_JIS", "EUC-JP", "Windows-1252");

    public DecodedSource decode(Path path) throws IOException {
        byte[] bytes = Files.readAllBytes(path);
        String detected = detect(bytes);
        Charset charset = charset(detected);
        if (charset == null) {
            charset = firstDecodable(bytes);
        }
        if (charset == null) {
            charset = StandardCharsets.UTF_8;
        }
        String text = charset.newDecoder()
                .onMalformedInput(CodingErrorAction.REPLACE)
                .onUnmappableCharacter(CodingErrorAction.REPLACE)
                .decode(ByteBuffer.wrap(bytes))
                .toString();
        return new DecodedSource(text, charset.name(), charset);
    }

    private String detect(byte[] bytes) {
        UniversalDetector detector = new UniversalDetector(null);
        detector.handleData(bytes, 0, bytes.length);
        detector.dataEnd();
        return detector.getDetectedCharset();
    }

    private Charset charset(String name) {
        if (name == null || name.isBlank()) {
            return null;
        }
        try {
            return Charset.forName(name);
        } catch (Exception ignored) {
            return null;
        }
    }

    private Charset firstDecodable(byte[] bytes) {
        Charset utf8 = StandardCharsets.UTF_8;
        try {
            utf8.newDecoder()
                    .onMalformedInput(CodingErrorAction.REPORT)
                    .onUnmappableCharacter(CodingErrorAction.REPORT)
                    .decode(ByteBuffer.wrap(bytes));
            return utf8;
        } catch (CharacterCodingException ignored) {
            for (String name : FALLBACK_CHARSETS) {
                Charset candidate = charset(name);
                if (candidate != null) {
                    return candidate;
                }
            }
        }
        return null;
    }

    public record DecodedSource(String text, String encoding, Charset charset) {

        public boolean hasGeneratedMarker() {
            String lower = text.toLowerCase(Locale.ROOT);
            int headerEnd = Math.min(lower.length(), 3000);
            String header = lower.substring(0, headerEnd);
            return header.contains("generated by") || header.contains("do not edit")
                    || header.contains("@generated");
        }
    }
}
